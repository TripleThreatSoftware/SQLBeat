-- ================================================================================================
-- Notification.dbo.messageRules
--
-- This table defines the recipients of alerts from SQLBeat. Each alert recipient may have any
-- number of rules in this table, and rules may be created which disable messages for all users by
-- leaving the user details empty. Rules which select messages to be sent are fired first, then
-- rules which select messages not to be sent are applied to the selected messages.
-- ================================================================================================
