CREATE TABLE [dbo].[messageRules](
	[ukey] [int] IDENTITY(1,1) NOT NULL,	-- An internally used incrementing identity counter; uniquely identifies this row, and may be used as a Foreign Key.
	[userName] [varchar](100) NULL,	-- A foreign key to USEREMAILS.USERNAME
	[sendMessage] [bit] NULL,	-- When this bit is set, it defines this rule as selecting a message to be sent
	[doNotSendMessage] [bit] NULL,	-- When this bit is set, messages matching these criteria will not be sent
	[messageLike] [varchar](500) NULL,	-- Enter any regular expression here
	[subjectLike] [varchar](500) NULL,	-- Enter any regular expression here
	[serverLike] [varchar](100) NULL,	-- Enter any regular expression here
	[serverEquals] [varchar](100) NULL,	-- Enter the fixed name of a server here, as found in the NotificationLog.ServerName field
	[severity] [int] NULL,	-- Use this field to filter based on severity (1,2 or 3) or leave it at 0 to select all messages
	[isJobFailure] [bit] NULL,	-- When this bit is set, messages about SQL Jobs will be sent
	[isLongRunningJob] [bit] NULL,	-- When this bit is set, messages about Long Running Jobs will be sent
	[isBlocking] [bit] NULL,	-- When this bit is set, messages about SQL Blocking will be sent
	[isLongRunningProcess] [bit] NULL,	-- When this bit is set, messages about Long Running Processes (sql) will be sent
	[isDriveSpace] [bit] NULL,	-- When this bit is set, messages about drive space will be sent
	[isLogSize] [bit] NULL,	-- When this bit is set, messages about SQL Log File size will be sent
	[isEventLog] [bit] NULL,	-- When this bit is set, messages from the Event Log Monitor module will be sent
	[isService] [bit] NULL,	-- When this bit is set, messages about Services will be sent
	[isConnectivity] [bit] NULL,	-- When this bit is set, messages about connectivity (sql or server) will be sent
	[isConfiguration] [bit] NULL,	-- When this bit is set, messages generated by the WMI Monitor module will be sent
	[isInstalledSoftware] [bit] NULL,	-- When this bit is set, messages from the Installed Software Monitor module will be sent
	[isFulfillment] [bit] NULL,	-- When this bit is set, fulfillment failure messages will be sent
	[isMonitorMessage] [bit] NULL,	-- When this bit is set, status messgaes about SQLBeat will be sent
	[businessHours] [bit] NULL,	-- When this bit is set, alerts will be sent during business hours
	[allMessages] [bit] NULL,	-- When this bit is set, the "is" series of bit fields are not expected to be set. Use this for all string matching alerts.
	[offHours] [bit] NULL,	-- When this bit is set, alerts will be sent during non-business hours
	[ukey_userEmail] [int] NULL,	-- Use this field to send messages to one (but not all) of a users email addresses
	[ukey_group] [int] NULL,	-- Use this field to filter messages based on the server group
	[ymd] [datetime] NULL,
